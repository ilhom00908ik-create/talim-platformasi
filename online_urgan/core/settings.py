def _env_flag(name, default):
    """`True`/`False` env bayrog'i (bo'sh qiymat — standart)."""
    raw = os.getenv(name)
    if raw is None or not str(raw).strip():
        return default
    return str(raw).strip().lower() in {'1', 'true', 'yes', 'on'}


